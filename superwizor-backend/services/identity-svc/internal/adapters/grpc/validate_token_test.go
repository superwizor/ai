func TestDerefString_NilSafe(t *testing.T) {
	assert.Equal(t, "", derefString(nil))
	s := "hello"
	assert.Equal(t, "hello", derefString(&s))
}

func TestToProtoUser_NullableFields(t *testing.T) {
	// Patient rows have nil firebase_uid and email (migration 000013)
	user := db.User{
		ID:          uuid.New(),
		Role:        "PATIENT",
		FirebaseUid: nil,
		Email:       nil,
	}

	proto := toProtoUser(user)
	assert.Equal(t, "", proto.FirebaseUid, "nil firebase_uid → empty string on wire")
	assert.Equal(t, "", proto.Email, "nil email → empty string on wire")
	assert.Equal(t, identityv1.UserRole_USER_ROLE_PATIENT, proto.Role)
}

func TestToProtoUser_OrganizationID(t *testing.T) {
	orgID := uuid.New()
	user := db.User{
		ID:             uuid.New(),
		Role:           "THERAPIST",
		OrganizationID: pgtype.UUID{Bytes: orgID, Valid: true},
	}

	proto := toProtoUser(user)
	assert.Equal(t, orgID.String(), proto.OrganizationId)
}

